@testable import IMAPToolLib
import Testing

@Suite
private enum HistogramTests {
    @Test
    static func emptyDurations() {
        #expect(TextHistogram(durations: []) == nil)
    }

    @Test
    static func durationsBars() {
        #expect(
            TextHistogram(durations: durations)?.textOutputLines == [
                "110ms-140ms: █55.9%██████████████████████████████▍                            ",
                "140ms-170ms: ███████████████████▉                                        30.6%",
                "170ms-200ms: █████▎                                                      8.06%",
                "200ms-230ms: ██▌                                                         3.76%",
                "230ms-260ms:                                                                0%",
                "260ms-290ms: ▊                                                           1.08%",
            ]
        )
    }

    @Test
    static func durationFormatting() {
        #expect(formatDuration(0.00123456) == "1.23ms")
        #expect(formatDuration(0.0123456) == "12.3ms")
        #expect(formatDuration(0.123456) == "123ms")
        #expect(formatDuration(1.23456) == "1,230ms")
        #expect(formatDuration(12.3456) == "12.3s")
        #expect(formatDuration(123.456) == "123s")
        #expect(formatDuration(1234.56) == "1,230s")
    }

    /// A width too narrow to hold the labels must not trap; every bin still
    /// produces a line.
    @Test(arguments: [1, 0, -10, 20])
    static func narrowWidthDoesNotCrash(width: Int) {
        let histogram = TextHistogram(durations: durations, width: width)
        #expect(histogram != nil)
        #expect(histogram?.textOutputLines.count == 6)
    }
}

